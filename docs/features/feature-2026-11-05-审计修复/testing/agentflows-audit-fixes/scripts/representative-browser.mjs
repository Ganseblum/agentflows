// Run with ego-browser nodejs; BASE_URL and EVIDENCE are explicit inputs.
const fs = await import('node:fs/promises');
const task = await taskSpace(25);
const page = task.page('p1');
const evidence = '/Users/lihanghang1/.zcode/v2/artifacts/agentflows-fixes-20261105-184849';
const results = [];
const expect = (condition, message) => { if (!condition) throw new Error(message); };
const status = async name => await page.evaluate(id => document.querySelector('[data-testid="'+id+'"]').textContent, name);
// CARD-2: actions are actual clicks; assertions observe the rendered result.
await page.click('[data-testid="load-error"]', {label:'检查加载失败状态'});
await page.waitForFunction(() => document.querySelector('[data-testid="status"]').textContent === '加载失败，请重试');
expect(await status('status') === '加载失败，请重试', 'failed state missing');
await page.click('[data-testid="load-success"]', {label:'验证失败后恢复成功'});
await page.waitForFunction(() => document.querySelector('[data-testid="status"]').textContent === '加载成功');
expect(await status('items') === '样本A', 'success item missing');
expect(!((await status('status')).includes('失败')), 'old error retained');
await page.click('[data-testid="load-empty"]', {label:'检查空列表状态'});
await page.waitForFunction(() => document.querySelector('[data-testid="status"]').textContent === '暂无数据');
expect(await status('items') === '', 'empty state retained old item');
await page.focus('[data-testid="load-success"]');
await page.press('[data-testid="load-success"]','Enter');
await page.waitForFunction(() => document.querySelector('[data-testid="items"]').textContent === '样本A');
results.push({card:'CARD-2',status:'pass',evidence:'browser',checks:['error','recover-success','empty','keyboard'],snapshot:await page.snapshot({scope:'full_page'})});
// CARD-3: inspect the actual HTTP result and the same form's visible outcome.
await page.fill('[data-testid="message-name"]','  测试者  ');
await page.click('[data-testid="message-submit"]', {label:'提交合法姓名并核对结果'});
await page.waitForFunction(() => document.querySelector('[data-testid="message-result"]').textContent === '已保存：测试者');
const before = await page.fetch('/api/state');
const initial = typeof before.body === 'string' ? JSON.parse(before.body) : before.body;
await page.fill('[data-testid="message-name"]','');
await page.click('[data-testid="message-submit"]', {label:'验证空姓名错误提示'});
await page.waitForFunction(() => document.querySelector('[data-testid="message-result"]').textContent === '姓名需为1到40个字符');
const invalid = await page.fetch('/api/messages',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({name:'x'.repeat(41)})});
expect(invalid.status === 422, 'long name did not return 422');
const state = await page.fetch('/api/state');
const after = typeof state.body === 'string' ? JSON.parse(state.body) : state.body;
expect(after.messages.length === initial.messages.length, 'invalid input changed message count');
results.push({card:'CARD-3',status:'pass',evidence:'browser+api',messageCount:after.messages.length,invalidStatus:invalid.status,snapshot:await page.snapshot({scope:'full_page'})});
// CARD-4: same-key concurrency is checked at the receiver, then actual double click.
const responses = await Promise.all([1,2].map(() => page.fetch('/api/actions',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({key:'audit-once'})})));
const payloads = responses.map(r => typeof r.body === 'string' ? JSON.parse(r.body) : r.body);
expect(responses.every(r => r.status === 200), 'same key request failed');
expect(payloads[0].operationId === payloads[1].operationId && payloads.every(p => p.count === 1), 'same key duplicated side effect');
await page.fill('[data-testid="action-key"]','audit-once');
const actionBounds = await page.evaluate(() => { const node=document.querySelector('[data-testid="action-submit"]');node.scrollIntoView({block:'center'});const r=node.getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}; });
await page.mouse.click(actionBounds.x,actionBounds.y,{clickCount:2,delay:0,label:'验证真实双击不重复执行'});
await page.waitForFunction(() => document.querySelector('[data-testid="action-result"]').textContent.startsWith('操作完成：'));
expect(await status('action-count') === '1', 'double click increased side effect count');
await page.fill('[data-testid="action-key"]','');
await page.click('[data-testid="action-submit"]', {label:'检查失败后按钮恢复'});
await page.waitForFunction(() => document.querySelector('[data-testid="action-result"]').textContent === '操作键需为1到80个字符');
expect(await page.evaluate(() => !document.querySelector('[data-testid="action-submit"]').disabled), 'button stuck disabled');
await page.fill('[data-testid="action-key"]','audit-next');
await page.click('[data-testid="action-submit"]', {label:'验证新操作独立执行'});
await page.waitForFunction(() => document.querySelector('[data-testid="action-count"]').textContent === '2');
const finalState = await page.fetch('/api/state');
const final = typeof finalState.body === 'string' ? JSON.parse(finalState.body) : finalState.body;
expect(final.count === 2 && final.operations.length === 2, 'operation receiver count differs');
results.push({card:'CARD-4',status:'pass',evidence:'browser+api',sameKeyOperation:payloads[0].operationId,finalCount:final.count,requestCount:final.requests,snapshot:await page.snapshot({scope:'full_page'})});
await fs.writeFile(evidence+'/representative-browser-results.json',JSON.stringify({spaceId:task.spaceId,url:await page.url(),results},null,2)+'\n');
console.log(JSON.stringify(results.map(({card,status,evidence})=>({card,status,evidence}))));
console.log(await page.snapshot({scope:'full_page'}));
